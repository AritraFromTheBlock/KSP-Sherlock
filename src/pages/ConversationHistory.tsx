// PDF export — pure browser, no external dependency required
// Uses jsPDF loaded dynamically to keep bundle lean
// ─────────────────────────────────────────────────────────────────────────────
async function exportSessionToPDF(session: ChatSession): Promise<void> {
  // Dynamic import so it only loads when needed
  const { jsPDF } = await import('jspdf');

  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
  const pageW = doc.internal.pageSize.getWidth();
  const pageH = doc.internal.pageSize.getHeight();
  const margin = 15;
  const contentW = pageW - margin * 2;
  let y = margin;

  const addPageIfNeeded = (needed: number) => {
    if (y + needed > pageH - margin) {
      doc.addPage();
      y = margin;
      drawPageHeader();
    }
  };

  const drawPageHeader = () => {
    doc.setFillColor(10, 14, 26);
    doc.rect(0, 0, pageW, 12, 'F');
    doc.setFontSize(7);
    doc.setTextColor(100, 116, 139);
    doc.text('KSP SHERLOCK — CONFIDENTIAL INVESTIGATION TRANSCRIPT', margin, 8);
    doc.text(`Page ${doc.getCurrentPageInfo().pageNumber}`, pageW - margin, 8, { align: 'right' });
  };

  // ── Cover block ──
  doc.setFillColor(10, 14, 26);
  doc.rect(0, 0, pageW, pageH, 'F');

  // Header stripe
  doc.setFillColor(0, 212, 170);
  doc.rect(0, 0, 6, pageH, 'F');

  // Title
  doc.setFontSize(22);
  doc.setTextColor(0, 212, 170);
  doc.setFont('helvetica', 'bold');
  doc.text('SHERLOCK', margin + 6, 38);

  doc.setFontSize(10);
  doc.setTextColor(148, 163, 184);
  doc.setFont('helvetica', 'normal');
  doc.text('KSP AI Crime Investigation Assistant', margin + 6, 46);

  doc.setDrawColor(30, 41, 59);
  doc.setLineWidth(0.4);
  doc.line(margin + 6, 52, pageW - margin, 52);

  doc.setFontSize(13);
  doc.setTextColor(226, 232, 240);
  doc.setFont('helvetica', 'bold');
  const titleLines = doc.splitTextToSize(`"${session.title}"`, contentW - 10);
  doc.text(titleLines, margin + 6, 62);

  y = 62 + titleLines.length * 7 + 6;

  // Meta table
  const metas = [
    ['Session ID', session.id],
    ['Date', session.timestamp],
    ['Total Messages', String(session.messages.length)],
    ['User Messages', String(session.messages.filter(m => m.sender === 'user').length)],
    ['AI Responses', String(session.messages.filter(m => m.sender === 'ai').length)],
    ['Export Time', new Date().toLocaleString('en-IN', { timeZone: 'Asia/Kolkata' })],
  ];

  metas.forEach(([label, value]) => {
    doc.setFontSize(8);
    doc.setTextColor(100, 116, 139);
    doc.setFont('helvetica', 'normal');
    doc.text(label + ':', margin + 6, y);
    doc.setTextColor(203, 213, 225);
    doc.text(value, margin + 55, y);
    y += 6;
  });

  y += 4;
  doc.setDrawColor(30, 41, 59);
  doc.line(margin + 6, y, pageW - margin, y);
  y += 8;

  // Audit badge
  doc.setFillColor(0, 212, 170, 0.08);
  doc.roundedRect(margin + 6, y, contentW - 6, 10, 2, 2, 'F');
  doc.setFontSize(7.5);
  doc.setTextColor(0, 212, 170);
  doc.setFont('helvetica', 'bold');
  doc.text('⚑  LOGGED AUDIT TRAIL — GENERATED BY KSP SHERLOCK NEURAL ENGINE', margin + 10, y + 6.5);
  y += 18;

  // ── Transcript pages ──
  doc.addPage();
  y = margin;
  drawPageHeader();
  y += 8;

  doc.setFontSize(11);
  doc.setTextColor(0, 212, 170);
  doc.setFont('helvetica', 'bold');
  doc.text('CONVERSATION TRANSCRIPT', margin, y);
  y += 8;

  session.messages.forEach((msg, idx) => {
    const isUser = msg.sender === 'user';

    addPageIfNeeded(18);

    // Sender label row
    doc.setFontSize(7.5);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(isUser ? 56 : 0, isUser ? 189 : 212, isUser ? 248 : 170);
    doc.text(isUser ? `[OFFICER]  ${msg.timestamp}` : `[SHERLOCK]  ${msg.timestamp}`, margin, y);
    y += 4;

    // Message bubble background
    const textLines = doc.splitTextToSize(msg.text, contentW - 8);
    const bubbleH = textLines.length * 4.5 + 6;

    addPageIfNeeded(bubbleH + 4);

    if (isUser) {
      doc.setFillColor(14, 40, 70);
    } else if (msg.isError) {
      doc.setFillColor(60, 10, 10);
    } else {
      doc.setFillColor(15, 23, 42);
    }
    doc.roundedRect(margin, y, contentW, bubbleH, 2, 2, 'F');

    doc.setFontSize(8.5);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(msg.isError ? 248 : 203, msg.isError ? 113 : 213, msg.isError ? 113 : 225);
    doc.text(textLines, margin + 4, y + 5);
    y += bubbleH + 6;

    // Divider every 5 messages
    if ((idx + 1) % 5 === 0) {
      addPageIfNeeded(6);
      doc.setDrawColor(30, 41, 59);
      doc.setLineWidth(0.2);
      doc.line(margin, y, pageW - margin, y);
      y += 4;
    }
  });

  // ── Footer ──
  addPageIfNeeded(20);
  y += 6;
  doc.setDrawColor(30, 41, 59);
  doc.line(margin, y, pageW - margin, y);
  y += 6;
  doc.setFontSize(7);
  doc.setTextColor(71, 85, 105);
  doc.text(
    'This document is generated by KSP SHERLOCK and is classified as a confidential law-enforcement record.',
    margin,
    y,
    { maxWidth: contentW }
  );
  y += 5;
  doc.text(
    'Unauthorised disclosure is a criminal offence under applicable laws.',
    margin,
    y
  );

  const safeTitle = session.title.replace(/[^a-z0-9]/gi, '_').substring(0, 40);
  doc.save(`KSP_SHERLOCK_${safeTitle}_${Date.now()}.pdf`);
}

